echo "            <div class='modal-footer'><button type='button' class='btn btn-outline-secondary btn-sm mb-0' data-bs-dismiss='modal'>".htmlspecialchars($layoutLabels['close'], ENT_QUOTES, 'UTF-8')."</button></div>";
